#!/usr/bin/env node

/**
 * Script to fetch Railway environment variables and create .env.production file
 * This allows using Railway env vars for building desktop and mobile apps
 * 
 * Usage:
 *   node scripts/fetch-railway-env.js
 *   RAILWAY_PROJECT_ID=xxx node scripts/fetch-railway-env.js
 */

import { execSync } from 'child_process';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Check if Railway CLI is installed
function checkRailwayCLI() {
  try {
    execSync('railway --version', { stdio: 'ignore' });
    return true;
  } catch (error) {
    return false;
  }
}

// Get Railway environment variables
function getRailwayEnvVars(projectId = null) {
  try {
    let command = 'railway variables --json';
    
    if (projectId) {
      command = `railway variables --project ${projectId} --json`;
    }
    
    // Try JSON output first (Railway CLI v2+)
    try {
      const output = execSync(command, { encoding: 'utf-8', stdio: 'pipe' });
      const json = JSON.parse(output);
      
      // Railway CLI JSON format: { variables: [{ name, value }] }
      if (json.variables && Array.isArray(json.variables)) {
        const envVars = {};
        json.variables.forEach(variable => {
          envVars[variable.name] = variable.value;
        });
        return envVars;
      }
      
      // Alternative format: direct object
      if (typeof json === 'object' && !json.variables) {
        return json;
      }
    } catch (jsonError) {
      // Fall back to text parsing if JSON fails
      console.log('JSON parsing failed, trying text format...');
    }
    
    // Fallback to text format parsing
    command = projectId ? `railway variables --project ${projectId}` : 'railway variables';
    const output = execSync(command, { encoding: 'utf-8', stdio: 'pipe' });
    
    // Parse Railway CLI text output
    const envVars = {};
    const lines = output.split('\n');
    
    for (const line of lines) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#') || trimmed.startsWith('Project:') || trimmed.startsWith('Environment:')) {
        continue;
      }
      
      // Handle KEY=VALUE format
      if (trimmed.includes('=')) {
        const match = trimmed.match(/^([^=]+)=(.*)$/);
        if (match) {
          const [, key, value] = match;
          if (key && value !== undefined) {
            envVars[key.trim()] = value.trim();
          }
        }
      }
      // Handle KEY: VALUE format (table format)
      else if (trimmed.includes(':')) {
        const parts = trimmed.split(':');
        if (parts.length >= 2) {
          const key = parts[0].trim();
          const value = parts.slice(1).join(':').trim();
          if (key && value) {
            envVars[key] = value;
          }
        }
      }
    }
    
    return envVars;
  } catch (error) {
    console.error('Error fetching Railway environment variables:', error.message);
    console.error('\nMake sure you are logged in to Railway CLI:');
    console.error('  railway login');
    console.error('\nOr provide RAILWAY_PROJECT_ID environment variable');
    console.error('\nAlternatively, set RAILWAY_TOKEN and RAILWAY_PROJECT_ID for API access');
    process.exit(1);
  }
}

// Get Railway environment variables using Railway API (alternative method)
async function getRailwayEnvVarsAPI(projectId, environmentId = null) {
  try {
    // This requires Railway API token
    const token = process.env.RAILWAY_TOKEN;
    if (!token) {
      throw new Error('RAILWAY_TOKEN environment variable is required for API method');
    }
    
    // Use native fetch (Node.js 18+)
    let url = `https://api.railway.app/v1/projects/${projectId}/variables`;
    if (environmentId) {
      url += `?environmentId=${environmentId}`;
    }
    
    const response = await fetch(url, {
      headers: {
        'Authorization': `Bearer ${token}`,
        'Content-Type': 'application/json'
      }
    });
    
    if (!response.ok) {
      throw new Error(`Railway API error: ${response.statusText}`);
    }
    
    const data = await response.json();
    const envVars = {};
    
    // Railway API returns variables in format: { variables: [{ name, value }] }
    if (data.variables) {
      data.variables.forEach(variable => {
        envVars[variable.name] = variable.value;
      });
    }
    
    return envVars;
  } catch (error) {
    console.error('Error fetching Railway environment variables via API:', error.message);
    throw error;
  }
}

// Generate .env.production file
function generateEnvFile(envVars, outputPath) {
  const lines = [
    '# Railway Environment Variables',
    '# Generated by scripts/fetch-railway-env.js',
    '# DO NOT EDIT THIS FILE MANUALLY - It will be overwritten',
    '',
  ];
  
  // Sort keys for consistent output
  const sortedKeys = Object.keys(envVars).sort();
  
  for (const key of sortedKeys) {
    const value = envVars[key];
    // Escape special characters in values
    const escapedValue = value.replace(/\\/g, '\\\\').replace(/\$/g, '\\$').replace(/`/g, '\\`');
    lines.push(`${key}=${escapedValue}`);
  }
  
  fs.writeFileSync(outputPath, lines.join('\n') + '\n', 'utf-8');
  console.log(`✓ Generated ${outputPath} with ${sortedKeys.length} environment variables`);
}

// Main function
async function main() {
  const projectId = process.env.RAILWAY_PROJECT_ID;
  // Use __dirname for ES modules, or process.cwd() as fallback
  const outputPath = path.join(process.cwd(), '.env.production');
  
  console.log('Fetching Railway environment variables...\n');
  
  let envVars = {};
  
  if (checkRailwayCLI()) {
    console.log('Using Railway CLI...');
    envVars = getRailwayEnvVars(projectId);
  } else if (process.env.RAILWAY_TOKEN && projectId) {
    console.log('Using Railway API...');
    envVars = await getRailwayEnvVarsAPI(projectId);
  } else {
    console.error('Error: Railway CLI not found and RAILWAY_TOKEN not set');
    console.error('\nPlease install Railway CLI:');
    console.error('  npm install -g @railway/cli');
    console.error('  railway login');
    console.error('\nOr set RAILWAY_TOKEN and RAILWAY_PROJECT_ID environment variables');
    process.exit(1);
  }
  
  if (Object.keys(envVars).length === 0) {
    console.warn('Warning: No environment variables found');
    console.warn('Make sure you are logged in and have access to the project');
    process.exit(1);
  }
  
  generateEnvFile(envVars, outputPath);
  console.log('\n✓ Done! You can now use Railway env vars for building.');
  console.log('  Run: npm run build:desktop or npm run build:mobile');
}

main().catch(error => {
  console.error('Fatal error:', error);
  process.exit(1);
});

